# apply-email-dedupe-and-matcher.sh
#
# Ships the source-of-record for two fixes that are ALREADY LIVE in Supabase:
#   1. Dropped the legacy "notify-admin-contractor" webhook trigger, which was
#      sending every new contractor a second welcome email and hello@ a second
#      application alert.
#   2. Widened service_specialty_map so "General Handyman" jobs reach the
#      handyman trades (and handymen see small painting/carpentry/drywall jobs).
#
# Also updates two edge-function sources for version control:
#   * notify-admin  v17 - now only the client's "request received" confirmation,
#                          with the stale "we'll match you and call you" copy
#                          replaced by the real estimates-then-you-pick flow.
#   * dispatch-job  v12 - the contractor email said "Jobs close after 3 bids";
#                          the cap has been 7 for a while. Now reads BID_CAP.
#
# Nothing here changes the running site on its own - the DB and edge functions
# were already deployed. This commit just stops the repo from drifting.
#
# Run:  bash ~/freddy-fixit/apply-email-dedupe-and-matcher.sh

set -euo pipefail

# Find the repo: prefer this script's own directory, then the usual spots.
SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TARGET=""
for cand in "$SELF_DIR" "$HOME/freddy-fixit" "$HOME/Desktop/freddy-fixit"; do
  if [ -d "$cand/.git" ] && [ -f "$cand/package.json" ]; then TARGET="$cand"; break; fi
done
if [ -z "$TARGET" ]; then
  echo "Could not find the freddy-fixit repo. Put this script inside it and run it again."
  exit 1
fi
cd "$TARGET"
echo "Repo: $TARGET"

# base64 -d on GNU, base64 -D on macOS/BSD.
b64dec() { base64 --decode 2>/dev/null || base64 -D; }

write_file() {
  local path="$1" want="$2"
  mkdir -p "$(dirname "$path")"
  b64dec > "$path"
  local got
  got="$(shasum -a 256 "$path" | awk '{print $1}')"
  if [ "$got" != "$want" ]; then
    echo "Checksum mismatch writing $path - nothing was pushed."
    exit 1
  fi
  echo "  ok  $path"
}

